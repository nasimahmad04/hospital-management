/* ---- 6.3 Bed occupancy follows admission status ---- */
CREATE OR REPLACE TRIGGER trg_admission_bed_status
AFTER INSERT OR UPDATE OF status ON admission
FOR EACH ROW
BEGIN
  IF INSERTING AND :NEW.status = 'ADMITTED' THEN
    UPDATE bed SET status = 'OCCUPIED' WHERE bed_id = :NEW.bed_id;
  ELSIF UPDATING AND :OLD.status = 'ADMITTED' AND :NEW.status <> 'ADMITTED' THEN
    UPDATE bed SET status = 'AVAILABLE' WHERE bed_id = :OLD.bed_id;
  END IF;
END;
