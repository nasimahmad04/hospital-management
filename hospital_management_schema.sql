/* ---- 6.1 Auto-generated business numbers ---- */
CREATE OR REPLACE TRIGGER trg_patient_bi_mrn
BEFORE INSERT ON patient FOR EACH ROW WHEN (NEW.mrn IS NULL)
BEGIN
  :NEW.mrn := 'MRN' || TO_CHAR(seq_mrn.NEXTVAL, 'FM00000000');
END;
/

CREATE OR REPLACE TRIGGER trg_appt_bi_no
BEFORE INSERT ON appointment FOR EACH ROW WHEN (NEW.appointment_no IS NULL)
BEGIN
  :NEW.appointment_no := 'APT' || TO_CHAR(SYSDATE, 'YYYYMM') || TO_CHAR(seq_appointment_no.NEXTVAL, 'FM000000');
END;
/

CREATE OR REPLACE TRIGGER trg_invoice_bi_no
