/* ---- 6.4 Dispensing: reject expired / insufficient stock and deduct quantity ---- */
CREATE OR REPLACE TRIGGER trg_dispense_stock
BEFORE INSERT ON medicine_dispense
FOR EACH ROW
DECLARE
  v_expiry DATE;
  v_onhand NUMBER;
BEGIN
  SELECT expiry_date, quantity_on_hand
    INTO v_expiry, v_onhand
    FROM medicine_batch
   WHERE batch_id = :NEW.batch_id
     FOR UPDATE;

  IF v_expiry < TRUNC(SYSDATE) THEN
    RAISE_APPLICATION_ERROR(-20001, 'Cannot dispense from an expired batch (batch_id=' || :NEW.batch_id || ').');
  END IF;

  IF v_onhand < :NEW.quantity THEN
    RAISE_APPLICATION_ERROR(-20002, 'Insufficient stock in batch ' || :NEW.batch_id ||
                            ' (on hand ' || v_onhand || ', requested ' || :NEW.quantity || ').');
  END IF;

  UPDATE medicine_batch
     SET quantity_on_hand = quantity_on_hand - :NEW.quantity
   WHERE batch_id = :NEW.batch_id;
END;
/

/* ---- 6.5 Invoice subtotal recalculated whenever items change (compound trigger
        avoids the "mutating table" error) ---- */
CREATE OR REPLACE TRIGGER trg_invoice_item_totals
FOR INSERT OR UPDATE OR DELETE ON invoice_item
COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  g_ids t_ids;

  AFTER EACH ROW IS
  BEGIN
    IF DELETING THEN
      g_ids(g_ids.COUNT + 1) := :OLD.invoice_id;
    ELSE
      g_ids(g_ids.COUNT + 1) := :NEW.invoice_id;
      IF UPDATING AND :OLD.invoice_id <> :NEW.invoice_id THEN
        g_ids(g_ids.COUNT + 1) := :OLD.invoice_id;
      END IF;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    FOR k IN 1 .. g_ids.COUNT LOOP
      UPDATE invoice
         SET subtotal = (SELECT NVL(SUM(line_total), 0)
                           FROM invoice_item
                          WHERE invoice_id = g_ids(k))
       WHERE invoice_id = g_ids(k);
    END LOOP;
  END AFTER STATEMENT;
END trg_invoice_item_totals;
