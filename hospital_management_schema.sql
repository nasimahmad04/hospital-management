/* ---------- 3.1 ORGANISATION ------------------------------------------------ */

CREATE TABLE hospital (
  hospital_id      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  hospital_name    VARCHAR2(150) NOT NULL,
  hospital_type    VARCHAR2(30)  DEFAULT 'GENERAL' NOT NULL,
  registration_no  VARCHAR2(50),
  area             VARCHAR2(100),
  road             VARCHAR2(100),
  building         VARCHAR2(100),
  city             VARCHAR2(80),
  state_province   VARCHAR2(80),
  postal_code      VARCHAR2(15),
  country          VARCHAR2(60)  NOT NULL,
  is_active        CHAR(1)       DEFAULT 'Y' NOT NULL,
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP,
  CONSTRAINT pk_hospital PRIMARY KEY (hospital_id),
  CONSTRAINT uq_hospital_name UNIQUE (hospital_name),
  CONSTRAINT ck_hospital_type CHECK (hospital_type IN ('GENERAL','SPECIALTY','TEACHING','CLINIC','TRAUMA_CENTER')),
  CONSTRAINT ck_hospital_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE hospital_contact (
  contact_id    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  hospital_id   NUMBER(10)    NOT NULL,
  contact_type  VARCHAR2(20)  DEFAULT 'MAIN' NOT NULL,
  phone         VARCHAR2(30),
  email         VARCHAR2(150),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_hospital_contact PRIMARY KEY (contact_id),
  CONSTRAINT fk_hcontact_hospital FOREIGN KEY (hospital_id) REFERENCES hospital (hospital_id) ON DELETE CASCADE,
