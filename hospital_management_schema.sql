  CONSTRAINT pk_app_user PRIMARY KEY (user_id),
  CONSTRAINT uq_app_user_name UNIQUE (username),
  CONSTRAINT uq_app_user_employee UNIQUE (employee_id),
  CONSTRAINT fk_app_user_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
  CONSTRAINT ck_app_user_role CHECK (role_code IN ('ADMIN','DOCTOR','NURSE','RECEPTION','PHARMACY','LAB','BILLING','HR')),
  CONSTRAINT ck_app_user_active CHECK (is_active IN ('Y','N'))
);

