CREATE TABLE payroll (
  payroll_id      NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  employee_id     NUMBER(10)   NOT NULL,
  period_start    DATE         NOT NULL,
  period_end      DATE         NOT NULL,
  basic_salary    NUMBER(12,2) DEFAULT 0 NOT NULL,
  hourly_rate     NUMBER(10,2),
  hours_worked    NUMBER(6,2),
  bonus_salary    NUMBER(12,2) DEFAULT 0 NOT NULL,
  compensation    NUMBER(12,2) DEFAULT 0 NOT NULL,     -- allowances / overtime
  deductions      NUMBER(12,2) DEFAULT 0 NOT NULL,     -- tax, PF, etc.
  net_salary      NUMBER(12,2) GENERATED ALWAYS AS (basic_salary + bonus_salary + compensation - deductions) VIRTUAL,
  status          VARCHAR2(10) DEFAULT 'DRAFT' NOT NULL,
  paid_on         DATE,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_payroll PRIMARY KEY (payroll_id),
  CONSTRAINT uq_payroll_period UNIQUE (employee_id, period_start, period_end),
  CONSTRAINT fk_payroll_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
  CONSTRAINT ck_payroll_period CHECK (period_end >= period_start),
  CONSTRAINT ck_payroll_amounts CHECK (basic_salary >= 0 AND bonus_salary >= 0 AND compensation >= 0 AND deductions >= 0),
  CONSTRAINT ck_payroll_status CHECK (status IN ('DRAFT','APPROVED','PAID','CANCELLED'))
);

